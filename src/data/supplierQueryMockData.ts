// 辅助函数：根据供应商类型和状态字段获取转换后的状态名称（不直接展示状态码）
export function getConvertedSupplierStatus(record: SupplierRecord): string {
  if (record.statusName) return record.statusName;
  const isAgent = record.supplierType === '智能体供应商';
  if (record.serviceStatus === '待审核') {
    return isAgent ? '审核中' : '接入联调';
  }
  if (record.serviceStatus === '已暂停') {
    return isAgent ? '已下架' : '已暂停';
  }
  return isAgent ? '已上架' : '正常接入';
}

